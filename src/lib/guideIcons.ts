export interface TalentRowLike {
	left: { picked: boolean };
	right: { picked: boolean };
}

/** 这一片叶子该不该点亮。`rows` 按 25 → 10 排。 */
export function branchLit(branchIndex: number, rows: TalentRowLike[]): boolean {
	const slot = BRANCH_SLOT[branchIndex];
	if (!slot) return false;
	const row = rows[slot[0]];
	if (!row) return false;
	return slot[1] === 'left' ? row.left.picked : row.right.picked;
}

/** 这一局点了几个天赋（用来决定底下亮几颗进度点）。 */
export function pickedCount(rows: TalentRowLike[]): number {
	return rows.reduce((sum, row) => sum + (row.left.picked ? 1 : 0) + (row.right.picked ? 1 : 0), 0);
}

/** 把一段色带写成 `<linearGradient>`。 */
function gradient(id: string, axis: [number, number, number, number], stops: Stop[]): string {
	const [x1, y1, x2, y2] = axis;
	return `<linearGradient id="${id}" gradientUnits="userSpaceOnUse" x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}">${stops
		.map(([offset, color]) => `<stop offset="${offset}" stop-color="${color}"/>`)
		.join('')}</linearGradient>`;
}

/**
 * 徽章每次画都自己带一份 `<defs>`，渐变 id 用调用序号区分。
 *
 * 一个页面里会同时挂好几个徽章（加点行里每一点一个、总结一格、悬停面板一个），
 * 固定 id 会撞车——`url(#x)` 永远解析到文档里第一个同名节点，那正是"两片叶子一起变色"
 * 这类怪现象的来源。带上序号就各自独立，代价是每个徽章多带一两 KB 的渐变定义，
 * 相对那一局的 JSON 不值一提。
 */
let badgeSeq = 0;

/**
 * 天赋徽章。`rows` 空（这场比赛没有回放数据）时就只剩弧线与灰树。
 *
 * 进度点按"点了几个就亮几颗"来点：STRATZ 那七颗点对应的原始数据我们拿不到，
 * 只能给一个说得通的映射，其余的树形、渐变与配色与他们一致。
 */
